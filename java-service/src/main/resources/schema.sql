MERGE INTO lead_suppression s USING (
    SELECT lead_id, BOOL_OR(unsubscribed) AS unsubscribed, BOOL_OR(blacklisted) AS blacklisted
    FROM (
        SELECT lead_id, unsubscribed, blacklisted FROM contact WHERE unsubscribed OR blacklisted
        UNION ALL
        SELECT a.lead_id, a.reason='UNSUBSCRIBED', a.reason='BLACKLISTED'
        FROM audit_event a JOIN lead l ON l.id=a.lead_id
        WHERE a.action='CONTACT_UPDATED' AND a.reason IN ('UNSUBSCRIBED','BLACKLISTED')
    ) evidence WHERE NOT EXISTS (SELECT 1 FROM data_migration WHERE name='backfill_lead_suppression')
    GROUP BY lead_id
) legacy ON s.lead_id=legacy.lead_id
WHEN MATCHED THEN UPDATE SET unsubscribed=s.unsubscribed OR legacy.unsubscribed,
                             blacklisted=s.blacklisted OR legacy.blacklisted
WHEN NOT MATCHED THEN INSERT (lead_id, unsubscribed, blacklisted)
    VALUES (legacy.lead_id, legacy.unsubscribed, legacy.blacklisted);
MERGE INTO data_migration(name) KEY(name) VALUES ('backfill_lead_suppression');

MERGE INTO audit_event event USING (
    WITH ordered AS (
        SELECT a.id, a.attempt_no, t.id AS target_id, a.action, a.reason,
               ROW_NUMBER() OVER (PARTITION BY t.id ORDER BY a.id) AS event_number,
               COUNT(*) OVER (PARTITION BY t.id) AS event_count
        FROM audit_event a JOIN task_target t ON t.task_id=a.task_id AND t.lead_id=a.lead_id
        WHERE a.action IN ('TARGET_ACCEPTED', 'TARGET_RETRY', 'TARGET_FAILED', 'TARGET_UNCERTAIN')
            AND NOT EXISTS (SELECT 1 FROM data_migration WHERE name='backfill_audit_attempt_number')
    ), matched AS (
        SELECT o.id, o.target_id, s.attempt_no, o.action,
            BOOL_AND(COALESCE(o.event_count=(SELECT COUNT(*) FROM send_attempt x WHERE x.target_id=o.target_id)
                AND (o.attempt_no IS NULL OR o.attempt_no=s.attempt_no) AND CASE o.action
                    WHEN 'TARGET_ACCEPTED' THEN s.outcome='ACCEPTED' AND o.reason='MOCK_ACCEPTED'
                    WHEN 'TARGET_RETRY' THEN s.outcome='TRANSIENT_ERROR' AND o.reason='TRANSIENT_ERROR'
                    WHEN 'TARGET_FAILED' THEN (s.outcome='PERMANENT_ERROR' AND o.reason='PERMANENT_ERROR')
                         OR (s.outcome='TRANSIENT_ERROR' AND o.reason='RETRY_EXHAUSTED')
                    WHEN 'TARGET_UNCERTAIN' THEN s.outcome='UNKNOWN_RESULT' AND o.reason='UNKNOWN_RESULT'
                    ELSE FALSE END, FALSE)) OVER (PARTITION BY o.target_id) AS all_match
        FROM ordered o LEFT JOIN send_attempt s ON s.target_id=o.target_id AND s.attempt_no=o.event_number
    ), accepted AS (
        SELECT target_id, MIN(attempt_no) AS attempt_no FROM matched
        WHERE all_match AND action='TARGET_ACCEPTED' GROUP BY target_id HAVING COUNT(*)=1
    )
    SELECT id, attempt_no FROM matched WHERE all_match
    UNION ALL
    SELECT a.id, accepted.attempt_no FROM audit_event a
        JOIN task_target t ON t.task_id=a.task_id AND t.lead_id=a.lead_id
        JOIN accepted ON accepted.target_id=t.id
        JOIN mock_receipt r ON r.target_id=t.id AND r.delivered_at IS NOT NULL
    WHERE a.action='TARGET_DELIVERED' AND a.reason='MOCK_RECEIPT'
        AND 1=(SELECT COUNT(*) FROM audit_event previous
            WHERE previous.task_id=a.task_id AND previous.lead_id=a.lead_id AND previous.action='TARGET_DELIVERED')
) legacy ON event.id=legacy.id
WHEN MATCHED AND event.attempt_no IS NULL THEN UPDATE SET attempt_no=legacy.attempt_no;
MERGE INTO data_migration(name) KEY(name) VALUES ('backfill_audit_attempt_number');

