CREATE OR REPLACE VIEW lead_selection AS
SELECT l.id AS lead_id,
    CASE WHEN l.manual_decision='APPROVE' THEN TRUE
         WHEN l.manual_decision='REJECT' THEN FALSE
         WHEN cfg.mode='RULES' THEN COALESCE(l.score_eligible AND l.rule_version=r.version, FALSE)
         ELSE COALESCE(cfg.auto_enabled AND cfg.provider_ready AND cfg.blocked_reason IS NULL AND s.status='SUCCEEDED' AND s.verdict='STRONG'
             AND s.profile_time=l.updated_at AND s.rule_version=r.version
             AND s.model=cfg.model AND s.prompt_version=cfg.prompt_version
             AND s.fixture_version=cfg.fixture_version, FALSE)
    END AS selected
FROM lead l CROSS JOIN semantic_settings cfg CROSS JOIN scoring_rules r
LEFT JOIN semantic_latest s ON s.lead_id=l.id
WHERE cfg.id=1 AND r.id=1;
