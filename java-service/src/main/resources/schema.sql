CREATE TABLE IF NOT EXISTS contact_suppression (
    contact_key VARCHAR(64) PRIMARY KEY,
    unsubscribed BOOLEAN NOT NULL,
    blacklisted BOOLEAN NOT NULL
);
MERGE INTO contact_suppression s USING (
    SELECT contact_key, BOOL_OR(unsubscribed) AS unsubscribed, BOOL_OR(blacklisted) AS blacklisted
    FROM contact WHERE unsubscribed OR blacklisted GROUP BY contact_key
) legacy ON s.contact_key=legacy.contact_key
WHEN MATCHED THEN UPDATE SET unsubscribed=s.unsubscribed OR legacy.unsubscribed,
                             blacklisted=s.blacklisted OR legacy.blacklisted
WHEN NOT MATCHED THEN INSERT (contact_key, unsubscribed, blacklisted)
    VALUES (legacy.contact_key, legacy.unsubscribed, legacy.blacklisted);

CREATE OR REPLACE VIEW contact_gate AS
SELECT c.contact_key, CASE
    WHEN BOOL_OR(c.blacklisted OR COALESCE(s.blacklisted, FALSE)) THEN 'BLACKLISTED'
    WHEN BOOL_OR(c.unsubscribed OR COALESCE(s.unsubscribed, FALSE)) THEN 'UNSUBSCRIBED'
    WHEN NOT BOOL_AND(c.authorized) THEN 'NO_CONSENT'
END AS block_reason
FROM contact c LEFT JOIN contact_suppression s ON s.contact_key=c.contact_key
GROUP BY c.contact_key;

