    lead_id BIGINT PRIMARY KEY REFERENCES lead(id),
    unsubscribed BOOLEAN NOT NULL,
    blacklisted BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS data_migration (
    name VARCHAR(100) PRIMARY KEY
);
CREATE OR REPLACE VIEW lead_contact_gate AS
SELECT c.lead_id, CASE
    WHEN COALESCE(s.blacklisted, FALSE) OR g.block_reason='BLACKLISTED' THEN 'BLACKLISTED'
    WHEN COALESCE(s.unsubscribed, FALSE) OR g.block_reason='UNSUBSCRIBED' THEN 'UNSUBSCRIBED'
    ELSE g.block_reason
END AS block_reason
FROM contact c JOIN contact_gate g ON g.contact_key=c.contact_key
LEFT JOIN lead_suppression s ON s.lead_id=c.lead_id;

